export const copy = (value) => JSON.parse(JSON.stringify(value));

export function titleOf(item, language) {
  return language === "mr"
    ? item.mrTitle || item.title || item.name
    : item.title || item.name;
}

export function imageUrl(url) {
  return url?.startsWith("/") ? url : url || "";
}

export function localizedText(item, englishKey, marathiKey, language) {
  if (language === "mr" && item?.[marathiKey]?.trim()) {
    return item[marathiKey];
  }
  return item?.[englishKey] || "";
}

const marathiStages = {
  Resolution: "ठराव",
  Developer: "विकसक",
  Agreement: "करार",
  Approvals: "मंजुरी",
  Construction: "बांधकाम",
  Possession: "ताबा",
};

export function localizedStage(stage, language) {
  return language === "mr" ? marathiStages[stage] || stage : stage;
}
